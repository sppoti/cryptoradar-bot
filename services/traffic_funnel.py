async def generate_branded_teaser_reel(
    bot_username: str,
    channel_tag: str = "@cryptoradar_live777",
    symbol: str = "BTCUSDT",
    partner_code: Optional[str] = None
) -> str:
    """
    Генерация персонализированного вертикального Reels-видео для партнера через generate_reel.
    """
    clean_code = (partner_code or "partner").replace("/", "_").replace("\\", "_")
    output_filename = f"reel_{clean_code}_{symbol.lower()}.mp4"
    
    reel_path = await generate_reel.generate_reel(
        symbol=symbol,
        bot_username=bot_username,
        channel_tag=channel_tag,
        output_filename=output_filename
    )
    return reel_path
